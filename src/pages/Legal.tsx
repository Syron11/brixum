function ContactDetails() {
  const links = storeContactLinks();
  return (
    <section className="legal-section">
      <h2>Связь с магазином</h2>
      <p>
        {store.sellerName || store.name}. {store.city}.{' '}
        {links.whatsapp && (
          <a href={links.whatsapp} target="_blank" rel="noopener noreferrer">
            WhatsApp: {contactPhone(store.whatsapp) || 'написать магазину'}
          </a>
        )}
      </p>
      {store.sellerId && <p>ИИН/БИН: {store.sellerId}</p>}
      {store.sellerAddress && <p>Адрес продавца: {store.sellerAddress}</p>}
      {store.email && (
        <p>
          Электронная почта: <a href={`mailto:${store.email}`}>{store.email}</a>
        </p>
      )}
    </section>
  );
}
